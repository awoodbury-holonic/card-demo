CREATE TABLE IF NOT EXISTS CARDEMO_TD_QUEUE (
	QUEUE_SEQUENCE BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	QUEUE_NAME VARCHAR(128) NOT NULL,
	RECORD_IMAGE VARCHAR(80) NOT NULL,
	CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_CARDEMO_TD_QUEUE_NAME_SEQUENCE
	ON CARDEMO_TD_QUEUE (QUEUE_NAME, QUEUE_SEQUENCE);
