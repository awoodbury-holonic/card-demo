CREATE TABLE IF NOT EXISTS PROGRAM_RESOURCE_RECORD (
	RESOURCE_NAME VARCHAR(128) NOT NULL,
	RECORD_KEY VARCHAR(512) NOT NULL,
	RECORD_IMAGE CHARACTER LARGE OBJECT NOT NULL,
	UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
	PRIMARY KEY (RESOURCE_NAME, RECORD_KEY)
);
CREATE INDEX IF NOT EXISTS IX_PROGRAM_RESOURCE_KEYSET
	ON PROGRAM_RESOURCE_RECORD (RESOURCE_NAME, RECORD_KEY);
