CREATE TABLE IF NOT EXISTS CARDEMO_REPORT_SUBMISSION (
	SUBMISSION_ID VARCHAR(36) PRIMARY KEY,
	REQUESTED_BY VARCHAR(128) NOT NULL,
	FIRST_SEQUENCE BIGINT NOT NULL,
	LAST_SEQUENCE BIGINT NOT NULL UNIQUE,
	SUBMITTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
	STATE VARCHAR(20) NOT NULL,
	EXECUTION_ID BIGINT
);
CREATE INDEX IF NOT EXISTS IX_REPORT_SUBMISSION_OWNER ON CARDEMO_REPORT_SUBMISSION (REQUESTED_BY, SUBMITTED_AT);
CREATE TABLE IF NOT EXISTS CARDEMO_REPORT_QUEUE_LOCK (LOCK_ID INTEGER PRIMARY KEY);
